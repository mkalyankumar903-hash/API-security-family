import {fixtureOperationV7} from "./security-fixture.js";
import Fastify from "fastify";
import {createHash} from "node:crypto";
import {performance} from "node:perf_hooks";
export type FixtureOperation={operationKey:string;method:"GET"|"HEAD";path:"/bills"|"/status"};
export const FIXTURE_ID="billing-safe-v1" as const;
const ALLOWED_PATHS=new Set(["/bills","/status"]);
export function fixtureOperation(method:string,path:string):boolean{
 return (method==="GET"||method==="HEAD")&&ALLOWED_PATHS.has(path);
}
const app=Fastify({logger:false,bodyLimit:1024});
app.get("/bills",async()=>[{id:"fixture-bill-1",amount:0}]);
app.get("/status",async()=>({fixture:"billing-safe-v1",healthy:true}));
// HEAD routes are automatically generated by Fastify for registered GET routes.
// This is a fixed in-memory Fastify injection transport, NEVER an outbound request.
export async function evaluateFixture(op:FixtureOperation):Promise<{
 httpStatus:number;responseBytes:number;responseHash:string;durationMs:number;outcome:string;
}>{
 if(process.env.NODE_ENV==="production"||process.env.PT_TEST_AUTHORITY_ENABLED!=="true")
  throw new Error("PRODUCTION_FIXTURE_EXECUTION_BLOCKED");
 if(!fixtureOperation(op.method,op.path))throw new Error("FIXTURE_OPERATION_UNAVAILABLE");
 const before=performance.now();
 const response=await app.inject({method:op.method,url:op.path,headers:{"x-lumicsec-fixture":"phase06"}});
 const data=Buffer.from(response.rawPayload);
 if(data.byteLength>2048)throw new Error("FIXTURE_RESPONSE_TOO_LARGE");
 const result={
  httpStatus:response.statusCode,responseBytes:data.byteLength,
  responseHash:createHash("sha256").update(data).digest("hex"),
  durationMs:Math.max(0,Math.ceil(performance.now()-before)),
  outcome:response.statusCode>=500?"FIXTURE_ERROR":"FIXTURE_RESPONSE"
 };
 return result;
}

/** Phase07 selection is governed by the same signed-permit and ledger authority.
 * Phase06 billing-safe-v1 fixture semantics are unchanged. */
export function fixtureOperationFor(fixtureId:string,method:string,path:string):boolean{
 if(fixtureId===FIXTURE_ID)return fixtureOperation(method,path);
 if(fixtureId==="pt-security-v1")return fixtureOperationV7(method,path);
 return false;
}
