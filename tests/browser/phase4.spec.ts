import {test,expect} from "@playwright/test";
import {drainQueue} from "../../packages/worker/src/index.js";
import {closeDatabase} from "../../packages/database/src/index.js";
test.afterAll(async()=>{await closeDatabase();});
test("real Chromium Phase04 full trusted fixture workflow, secure vs BOLA, evidence, history and tenant denial",async({page,request})=>{
 test.setTimeout(125000);
 const external:string[]=[];page.on("request",r=>{if(r.url().includes(".fixture.invalid"))external.push(r.url());});
 const suffix=crypto.randomUUID().slice(0,8);
 await page.goto("/");
 await page.getByPlaceholder("Payments API").fill("Auth04 "+suffix);
 await page.getByPlaceholder("https://api.example.invalid").fill("https://auth04-"+suffix+".fixture.invalid");
 await page.getByRole("button",{name:"Register target"}).click();
 await page.getByLabel(/OpenAPI 3.0 \/ 3.1, Swagger 2.0 JSON\/YAML or Postman Collection/)
  .setInputFiles("fixtures/phase2-openapi30-v1.json");
 await expect(page.getByRole("status").filter({hasText:/Imported OPENAPI_3_0/})).toBeVisible();
 const region=page.getByRole("region",{name:"Synthetic authenticated assessment"});
 await region.getByRole("button",{name:"Refresh imported versions, profiles & history"}).click();
 await expect(region.getByLabel("Specification version for synthetic authentication")).not.toHaveValue("");
 await expect(region.getByText("BearerAuth")).toBeVisible();
 await region.getByRole("button",{name:"Register opaque reference"}).click();
 await expect(region.getByRole("status")).toContainText("Opaque reference registered");
 await region.getByLabel("Fixture version").selectOption("secure-v1");
 await region.getByLabel("Synthetic authentication scheme").selectOption("BEARER");
 await region.getByLabel("Trusted identity profile").selectOption("user-a");
 await region.getByRole("button",{name:"Create synthetic identity profile"}).click();
 await expect(region.getByText(/validation: PENDING/)).toBeVisible();
 await region.getByRole("button",{name:"Validate fixture readiness"}).click();
 await expect(region.getByRole("status").filter({hasText:"Fixture-ready"})).toContainText("Fixture-ready");
 await region.getByRole("button",{name:"Start isolated authenticated assessment"}).click();
 await expect(region.getByRole("status").filter({hasText:"Authenticated assessment status:"})).toContainText("QUEUED");
 expect(await drainQueue()).toBe(1);
 await expect(region.getByText(/21 real in-memory evaluations/)).toBeVisible();
 await expect(region.getByText(/No deviations in this fixture/)).toBeVisible();
 const appBase="http://127.0.0.1:3001",auth={authorization:"Bearer local-test-token-alpha"};
 const targetRes=await request.get(appBase+"/v1/targets",{headers:auth});
 const tid=(await targetRes.json() as {id:string;name:string}[]).find(t=>t.name==="Auth04 "+suffix)?.id;
 expect(tid).toBeTruthy();
 const before=await request.get(appBase+"/v4/targets/"+tid+"/assessments",{headers:auth});
 const first=(await before.json() as {id:string}[])[0]?.id;
 if(!first)throw new Error("FIRST_ASSESSMENT_MISSING");
 const forbidden=await request.get(appBase+"/v4/assessments/"+first,{headers:{authorization:"Bearer local-test-token-beta"}});
 expect(forbidden.status()).toBe(404);
 await region.getByLabel("Fixture version").selectOption("broken-bola-v1");
 await region.getByLabel("Synthetic authentication scheme").selectOption("OAUTH2");
 await region.getByRole("button",{name:"Create synthetic identity profile"}).click();
 await expect(region.getByText(/validation: PENDING/)).toBeVisible();
 await region.getByRole("button",{name:"Validate fixture readiness"}).click();
 await expect(region.getByRole("status").filter({hasText:"Fixture-ready"})).toContainText("Fixture-ready");
 await region.getByRole("button",{name:"Start isolated authenticated assessment"}).click();
 await expect(region.getByRole("status").filter({hasText:"Authenticated assessment status:"})).toContainText("QUEUED");
 expect(await drainQueue()).toBe(1);
 await expect(region.getByText(/1 fixture-only deviations/)).toBeVisible();
 await region.getByLabel("Filter fixture evaluations").selectOption("DEVIATION");
 await expect(region.getByRole("cell",{name:"AUTH04_CROSS_USER_BOLA"})).toBeVisible();
 await region.getByRole("button",{name:"Inspect redacted fixture evidence"}).click();
 await expect(region.getByText("Redacted evidence detail")).toBeVisible();
 const body=await region.textContent();
 expect(body).toContain("Fixture-only observation");
 expect(body).not.toMatch(/Bearer [A-Za-z0-9_-]{20,}/);
 await region.getByLabel("Historical assessment").selectOption(first);
 await region.getByRole("button",{name:"Compare historical runs"}).click();
 await expect(region.getByText(/New fixture observations: 1/)).toBeVisible();
 expect(external).toEqual([]);
});
