import {test,expect} from "@playwright/test";
import {drainQueue} from "../../packages/worker/src/index.js";
import {closeDatabase} from "../../packages/database/src/index.js";
test.afterAll(async()=>{await closeDatabase();});
test("real Chromium: imported OpenAPI 3.0 → queued real worker → evidence → persistent report → cross-version comparison",async({page,request})=>{
 const suffix=crypto.randomUUID().slice(0,8),external:string[]=[];
 page.on("request",r=>{if(r.url().includes(".fixture.invalid"))external.push(r.url());});
 await page.goto("/");
 await page.getByPlaceholder("Payments API").fill("Phase03 "+suffix);
 await page.getByPlaceholder("https://api.example.invalid").fill("https://phase03-"+suffix+".fixture.invalid");
 await page.getByRole("button",{name:"Register target"}).click();
 const uploader=page.getByLabel(/OpenAPI 3.0 \/ 3.1, Swagger 2.0 JSON\/YAML or Postman Collection/);
 await uploader.setInputFiles("fixtures/phase2-openapi30-v1.json");
 await expect(page.getByRole("status").filter({hasText:/Imported OPENAPI_3_0/})).toBeVisible();
 const detection=page.getByRole("region",{name:"Deterministic API detection"});
 await detection.getByRole("button",{name:"Refresh imported versions & history"}).click();
 await expect(detection.getByLabel("Specification version for deterministic assessment")).not.toHaveValue("");
 await detection.getByRole("button",{name:"Start deterministic SPEC_ONLY assessment"}).click();
 await expect(detection.getByRole("status").filter({hasText:"Deterministic assessment status:"})).toContainText("QUEUED");
 expect(await drainQueue()).toBe(1);
 await expect(detection.getByRole("heading",{name:"Evidence-backed assessment report"})).toBeVisible();
 await expect(detection.getByText("Runtime verification not performed.",{exact:false})).toBeVisible();
 await detection.getByRole("button",{name:"Inspect evidence"}).first().click();
 await expect(detection.getByRole("heading",{name:/Evidence detail/})).toBeVisible();
 await expect(detection.getByText(/Source pointer:/)).toBeVisible();
 await expect(detection.getByRole("button",{name:"Download immutable JSON report"})).toBeVisible();
 await uploader.setInputFiles("fixtures/phase2-openapi30-v2.json");
 await expect(page.getByRole("status").filter({hasText:/Imported OPENAPI_3_0 v2/})).toBeVisible();
 await detection.getByRole("button",{name:"Refresh imported versions & history"}).click();
 const selector=detection.getByLabel("Specification version for deterministic assessment");
 const options=await selector.locator("option").allTextContents();expect(options.some(x=>x.includes("v2"))).toBeTruthy();
 const next=await selector.locator("option").evaluateAll(opts=>opts.map(o=>({label:o.textContent??"",value:(o as HTMLOptionElement).value})).find(o=>o.label.includes("v2"))?.value);
 if(!next)throw new Error("PHASE3_VERSION_2_MISSING");await selector.selectOption(next);
 await detection.getByRole("button",{name:"Start deterministic SPEC_ONLY assessment"}).click();
 expect(await drainQueue()).toBe(1);
 await expect(detection.getByRole("heading",{name:"Evidence-backed assessment report"})).toBeVisible();
 await detection.getByRole("button",{name:"Refresh imported versions & history"}).click();
 await detection.getByRole("button",{name:"Compare assessment observations"}).click();
 await expect(detection.getByRole("heading",{name:"Evidence-aware comparison"})).toBeVisible();
 const specRows=(await request.get("http://127.0.0.1:3001/v3/detection/rules?limit=100",
 {headers:{authorization:"Bearer local-test-token-beta"}}));expect(specRows.ok()).toBeTruthy();
 expect(external).toEqual([]);
});
