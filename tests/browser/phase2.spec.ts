import {test,expect} from "@playwright/test";
import {drainQueue} from "../../packages/worker/src/index.js";
import {closeDatabase} from "../../packages/database/src/index.js";
const token="local-test-token-alpha",api="http://127.0.0.1:3001";
test.afterAll(async()=>{await closeDatabase();});
test("real Chromium: all offline imports, React explorer, version diff, selected 3.1 SPEC_ONLY and history",async({page,request})=>{
 const external:string[]=[];
 page.on("request",req=>{if(req.url().startsWith("https://api.fixture.invalid"))external.push(req.url());});
 const suffix=crypto.randomUUID().slice(0,8);
 await page.goto("/");
 await page.getByPlaceholder("Payments API").fill("Phase2 Explorer "+suffix);
 await page.getByPlaceholder("https://api.example.invalid").fill("https://explorer-"+suffix+".fixture.invalid");
 await page.getByRole("button",{name:"Register target"}).click();
 await expect(page.getByLabel("Select target")).not.toHaveValue("");
 const targetId=await page.getByLabel("Select target").inputValue();
 await expect(page.getByRole("heading",{name:"API specification & offline discovery · Phase 2"})).toBeVisible();
 const uploader=page.getByLabel(/OpenAPI 3.0 \/ 3.1, Swagger 2.0 JSON\/YAML or Postman Collection/);
 await uploader.setInputFiles("fixtures/phase2-openapi30-v1.json");
 await expect(page.getByRole("status").filter({hasText:/Imported OPENAPI_3_0 v1/})).toBeVisible();
 await expect(page.getByText("GET").filter({hasText:""}).first()).toBeVisible();
 await page.getByRole("button",{name:"Inspect operation"}).first().click();
 await expect(page.getByRole("heading",{name:/Operation details · GET \/bills/})).toBeVisible();
 await expect(page.getByText(/Effective auth: INHERITED/)).toBeVisible();
 await expect(page.getByText(/limit/).first()).toBeVisible();
 await uploader.setInputFiles("fixtures/phase2-openapi30-v2.json");
 await expect(page.getByRole("status").filter({hasText:/Imported OPENAPI_3_0 v2/})).toBeVisible();
 await page.getByRole("button",{name:"Compare structural versions"}).click();
 await expect(page.getByRole("heading",{name:"Structural diff — review required"})).toBeVisible();
 await expect(page.getByText("POST /bills",{exact:true}).first()).toBeVisible();
 await expect(page.getByText("GET /status",{exact:true}).first()).toBeVisible();
 await uploader.setInputFiles("fixtures/phase2-postman21.json");
 await expect(page.getByRole("status").filter({hasText:/Imported POSTMAN_2_1 v3/})).toBeVisible();
 await expect(page.getByText(/UNRESOLVED_COLLECTION_VARIABLES/)).toBeHidden(); // collapsed details until expansion
 await page.getByText(/Import coverage warnings/).click();
 await expect(page.getByText("POSTMAN_SCRIPT_IGNORED")).toBeVisible();
 await expect(page.getByText(/Ineligible: legacy rules do not support this format/).first()).toBeVisible();
 await uploader.setInputFiles("fixtures/phase2-openapi31.yaml");
 await expect(page.getByRole("status").filter({hasText:/Imported OPENAPI_3_1 v4/})).toBeVisible();
 const rows=page.getByRole("row");
 await expect(rows.filter({hasText:"OPENAPI_3_1"})).toHaveCount(1);
 await page.getByRole("button",{name:"Select for SPEC_ONLY"}).click();
 await expect(page.getByRole("status").filter({hasText:/Version selected for existing SPEC_ONLY/})).toBeVisible();
 await page.getByRole("button",{name:"Start SPEC_ONLY assessment"}).click();
 await expect(page.getByRole("status").filter({hasText:"Assessment status:"})).toContainText("QUEUED");
 expect(await drainQueue()).toBe(1);
 await expect(page.getByRole("heading",{name:"4. Evidence-backed report"})).toBeVisible();
 await expect(page.getByText(/0 confirmed runtime vulnerabilities/)).toBeVisible();
 const foreign=await request.get(api+"/v2/targets/"+targetId+"/specifications",{headers:{authorization:"Bearer local-test-token-beta"}});
 expect(foreign.status()).toBe(404);
 await uploader.setInputFiles({name:"malformed.json",mimeType:"application/json",buffer:Buffer.from("{PRIVATE_TOKEN=do-not-return")});
 await expect(page.getByRole("alert")).toContainText(/Import FAILED: INVALID_JSON/);
 await expect(page.getByText("FAILED",{exact:true})).toBeVisible();
 await page.getByRole("button",{name:"Suspend target"}).click();
 await expect(page.getByText(/Lifecycle:.*SUSPENDED/)).toBeVisible();
 await expect(uploader).toBeDisabled();
 const denied=await request.post(api+"/v2/targets/"+targetId+"/specifications/imports",{headers:{authorization:"Bearer "+token,"idempotency-key":"suspended-"+crypto.randomUUID()},data:{filename:"test.json",content:"{}"}});
 expect(denied.status()).toBe(409);
 expect(external).toEqual([]);
});
