import {test,expect} from "@playwright/test";
import {drainQueue} from "../../packages/worker/src/index.js";
import {closeDatabase} from "../../packages/database/src/index.js";
test.afterAll(async()=>{await closeDatabase();});
test("Phase05 real Chromium: unified persisted assessment, findings, provenance, export, history and version comparison",async({page,request})=>{
 test.setTimeout(125000);
 const unsafe:string[]=[];page.on("request",r=>{if(r.url().includes(".fixture.invalid"))unsafe.push(r.url());});
 const suffix=crypto.randomUUID().slice(0,8);
 await page.goto("/");
 await page.getByPlaceholder("Payments API").fill("Unified05 "+suffix);
 await page.getByPlaceholder("https://api.example.invalid").fill("https://unified05-"+suffix+".fixture.invalid");
 await page.getByRole("button",{name:"Register target"}).click();
 const workspace=page.getByRole("region",{name:"Unified assessment workspace"});
 await expect(workspace.getByRole("heading",{name:"API Assessment Workspace"})).toBeVisible();
 await expect(workspace.getByLabel("Assessment type")).toBeVisible();
 await expect(workspace.getByText(/Only trusted test fixtures/)).toHaveCount(0);
 await workspace.getByLabel("Assessment type").selectOption("auth-fixture-v1");
 await expect(workspace.getByText(/Only trusted test fixtures/)).toBeVisible();
 await workspace.getByLabel("Assessment type").selectOption("inventory-v1");
 const uploader=page.getByLabel(/OpenAPI 3.0 \/ 3.1, Swagger 2.0 JSON\/YAML or Postman Collection/);
 await uploader.setInputFiles("fixtures/phase2-openapi30-v1.json");
 await expect(page.getByRole("status").filter({hasText:/Imported OPENAPI_3_0/})).toBeVisible();
 const detection=page.getByRole("region",{name:"Deterministic API detection"});
 await detection.getByRole("button",{name:"Refresh imported versions & history"}).click();
 await detection.getByRole("button",{name:"Start deterministic SPEC_ONLY assessment"}).click();
 expect(await drainQueue()).toBe(1);
 await expect(detection.getByRole("heading",{name:"Evidence-backed assessment report"})).toBeVisible();
 await workspace.getByRole("button",{name:"Refresh assessment history"}).click();
 await expect(workspace.getByRole("cell",{name:"COMPLETED"}).first()).toBeVisible();
 await workspace.getByRole("button",{name:"Review run"}).first().click();
 await expect(workspace.getByRole("heading",{name:"Immutable report"})).toBeVisible();
 await expect(workspace.getByRole("heading",{name:"Coverage and unknowns"})).toBeVisible();
 await expect(workspace.getByRole("heading",{name:"Unified findings"})).toBeVisible();
 await expect(workspace.getByText(/Runtime security not verified/)).toBeVisible();
 await workspace.getByRole("button",{name:"View persisted evidence"}).first().click();
 await expect(workspace.getByRole("heading",{name:/Finding evidence:/})).toBeVisible();
 await expect(workspace.getByText(/Fix applied does not mean VERIFIED_FIXED/)).toBeVisible();
 await expect(workspace.getByRole("button",{name:"Export persisted JSON report"})).toBeEnabled();
 const host="http://127.0.0.1:3001",header={authorization:"Bearer local-test-token-alpha"};
 const res=await request.get(host+"/v1/targets",{headers:header});
 const tid=(await res.json() as {id:string;name:string}[]).find(t=>t.name==="Unified05 "+suffix)?.id;
 if(!tid)throw new Error("TEST_TARGET_MISSING");
 const history=await request.get(host+"/v5/assessments?targetId="+tid,{headers:header});
 const first=(await history.json() as {id:string}[])[0]?.id;if(!first)throw new Error("TEST_RUN_MISSING");
 const old=await request.get(host+"/v5/assessments/"+first+"/report",{headers:header});
 expect(old.ok()).toBeTruthy();
 const forbidden=await request.get(host+"/v5/assessments/"+first+"/export",
  {headers:{authorization:"Bearer local-test-token-beta"}});
 expect(forbidden.status()).toBe(404);
 await uploader.setInputFiles("fixtures/phase2-openapi30-v2.json");
 await expect(page.getByRole("status").filter({hasText:/Imported OPENAPI_3_0 v2/})).toBeVisible();
 await detection.getByRole("button",{name:"Refresh imported versions & history"}).click();
 const select=detection.getByLabel("Specification version for deterministic assessment");
 const version=await select.locator("option").evaluateAll(opts=>opts.map(x=>({value:(x as HTMLOptionElement).value,label:x.textContent??""})).find(x=>x.label.includes("v2"))?.value);
 if(!version)throw new Error("TEST_V2_MISSING");
 await select.selectOption(version);
 await detection.getByRole("button",{name:"Start deterministic SPEC_ONLY assessment"}).click();
 expect(await drainQueue()).toBe(1);
 await workspace.getByRole("button",{name:"Refresh assessment history"}).click();
 await expect(workspace.getByRole("button",{name:"Review run"})).toHaveCount(2);
 const combos=workspace.getByLabel("Baseline completed run").locator("option");
 await expect(combos).toHaveCount(3);
 await workspace.getByLabel("Baseline completed run").selectOption({index:1});
 await workspace.getByLabel("New completed run").selectOption({index:2});
 await workspace.getByRole("button",{name:"Compare persisted findings"}).click();
 await expect(workspace.getByRole("heading",{name:"Comparison results"})).toBeVisible();
 await expect(workspace.getByText(/No longer observed never means VERIFIED_FIXED/)).toBeVisible();

 // Actual Chromium customer flow for new phase05-v2 on a newly imported specification.
 await workspace.getByLabel("Assessment type").selectOption("inventory-v2");
 await workspace.getByRole("button",{name:"Refresh imported specification versions"}).click();
 const richSelect=workspace.getByLabel("Imported immutable specification");
 await expect(richSelect.locator("option")).toHaveCount(2);
 await richSelect.selectOption(version);
 await workspace.getByRole("button",{name:"Start selected offline assessment"}).click();
 await expect(workspace.getByText(/Queued assessment:/)).toBeVisible();
 expect(await drainQueue()).toBe(1);
 await workspace.getByRole("button",{name:"Refresh assessment history"}).click();
 await expect(workspace.getByRole("button",{name:"Review run"})).toHaveCount(3);
 await workspace.getByRole("button",{name:"Review run"}).first().click();
 await expect(workspace.getByText(/inventory-v2/).first()).toBeVisible();
 const richHistory=await request.get(host+"/v5/assessments?targetId="+tid+"&engineVersion=inventory-v2",{headers:header});
 const richRows=await richHistory.json() as {id:string;engineVersion:string}[];
 expect(richRows.length).toBe(1);
 const richReport=await request.get(host+"/v5/assessments/"+richRows[0]!.id+"/report",{headers:header});
 expect(richReport.status()).toBe(200);
 const richPayload=await richReport.json() as {immutableReport:{engineVersion:string;coverage:{ruleId:string;status:string}[]};verifiedFixed:boolean};
 expect(richPayload.immutableReport.engineVersion).toBe("inventory-v2");
 expect(richPayload.immutableReport.coverage.find(x=>x.ruleId==="API03_AUTH_OVERRIDE_WEAKENS")?.status).toBe("EVALUATED");
 expect(richPayload.verifiedFixed).toBe(false);
 const immutable=await request.get(host+"/v5/assessments/"+first+"/report",{headers:header});
 expect(await immutable.text()).toBe(await old.text());
 expect(unsafe).toEqual([]);
});
