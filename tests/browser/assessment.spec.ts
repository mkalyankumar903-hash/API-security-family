import {test,expect} from "@playwright/test";
import {drainQueue} from "../../packages/worker/src/index.js";
import {closeDatabase} from "../../packages/database/src/index.js";
test.afterAll(async()=>{await closeDatabase();});
test("real Chromium frontend + Fastify + PostgreSQL SPEC_ONLY and authorization denial",async({page,request})=>{
  const token="local-test-token-alpha";
  const suffix=crypto.randomUUID();
  await page.goto("/");
  await expect(page.getByRole("heading",{name:"API Security Assessment"})).toBeVisible();
  await expect(page.getByLabel("Select target")).toBeVisible();
  await page.getByPlaceholder("Payments API").fill("Browser "+suffix);
  await page.getByPlaceholder("https://api.example.invalid").fill("https://api."+suffix+".fixture.invalid");
  await page.getByRole("button",{name:"Register target"}).click();
  const selector=page.getByLabel("Select target");
  await expect(selector).toHaveValue(/.+/);
  const targetId=await selector.inputValue();
  const specInput=page.getByLabel("Specification file");
  await specInput.setInputFiles("fixtures/insecure.openapi.json");
  await expect(page.getByText("/admin/accounts")).toBeVisible();
  await page.getByRole("button",{name:"Start SPEC_ONLY assessment"}).click();
  await expect(page.getByRole("status").filter({hasText:"Assessment status:"})).toContainText("QUEUED");
  expect(await drainQueue()).toBe(1);
  await expect(page.getByRole("heading",{name:"4. Evidence-backed report"})).toBeVisible({timeout:10000});
  await expect(page.getByText("SPEC_OBSERVATION · SPEC_ONLY · Review required").first()).toBeVisible();
  await expect(page.getByText("Runtime validation: false")).toBeVisible();
  const foreign=await request.get("http://127.0.0.1:3001/v1/targets/"+targetId,{headers:{authorization:"Bearer local-test-token-beta"}});
  expect(foreign.status()).toBe(404);
  const targets=await request.get("http://127.0.0.1:3001/v1/targets",{headers:{authorization:"Bearer "+token}});
  expect((await targets.json()).some((t:{id:string})=>t.id===targetId)).toBe(true);
  await page.getByLabel("Synthetic development token (never a production login)").fill("invalid-browser-token");
  await expect(page.getByRole("alert")).toContainText(/Access denied.*PERMISSION_DENIED/);
});
